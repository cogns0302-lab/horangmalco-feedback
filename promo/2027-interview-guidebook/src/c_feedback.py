def C(text="", *a, **k):
    """("·근거: ", 문단, 글자) 같은 꼬리표와 바로 뒤 문장을 한 문단으로 합친다(꼬리표는 굵게)."""
    if isinstance(text, list):
        out, hold = [], None
        for it in text:
            if isinstance(it, tuple) and it[0].endswith(": "):
                hold = it[0].strip()
            elif hold is not None and type(it) is str:
                out.append(f"**{hold}** {it.strip()}")
                hold = None
            else:
                out.append(it)
        text = out
    return _C(text, *a, **k)

